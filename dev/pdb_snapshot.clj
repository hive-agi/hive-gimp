(ns pdb-snapshot
  "Generate a PDB spec EDN for `hive-gimp.pdb.native/defprocedures` from a
   live GIMP `describe`.

       clojure -M:pdb-snapshot resources/hive_gimp/pdb/starter.edn 9877 \\
         plug-in-despeckle:despeckle gimp-drawable-invert:invert-drawable \\
         file-png-export:export-png

   Each argument is `procedure` or `procedure:fn-name`. Writes the file only
   when every procedure was described; otherwise prints the refusal and
   exits 1."
  (:require [clojure.pprint :as pprint]
            [clojure.string :as str]
            [hive-gimp.pdb :as pdb]
            [hive-gimp.pdb.derive :as derive]
            [hive-gimp.response :as response]
            [hive-gimp.transport.socket :as socket]))

